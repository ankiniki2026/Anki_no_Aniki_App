function getSystemLanguage(): Language {
  try {
    let localeStr = '';
    if (typeof navigator !== 'undefined' && navigator.language) {
      localeStr = navigator.language;
    } else if (typeof Intl !== 'undefined' && Intl.DateTimeFormat) {
      localeStr = Intl.DateTimeFormat().resolvedOptions().locale || '';
    }
    const langCode = localeStr.split(/[-_]/)[0].toLowerCase();
    if (langCode === 'ja') return 'ja';
    if (langCode === 'fr') return 'fr';
    if (langCode === 'fi') return 'fi';
    if (langCode === 'en') return 'en';
    return 'en';
  } catch {
    return 'ja';
  }
}

const LanguageContext = createContext<{
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof typeof translations['ja'], params?: Record<string, string | number>) => string;
}>({
  language: 'ja',
  setLanguage: () => {},
  t: (key) => translations['ja'][key] || key,
});

export const useLanguage = () => useContext(LanguageContext);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => getSystemLanguage());

  useEffect(() => {
    const loadLanguage = async () => {
      const savedLanguage = await AsyncStorage.getItem('language');
      if (savedLanguage && (['ja', 'en', 'fr', 'fi'] as Language[]).includes(savedLanguage as Language)) {
        setLanguageState(savedLanguage as Language);
      } else {
        setLanguageState(getSystemLanguage());
      }
    };
    loadLanguage();
  }, []);

  const setLanguage = async (lang: Language) => {
    setLanguageState(lang);
    await AsyncStorage.setItem('language', lang);
  };

  const t = (key: keyof typeof translations['ja'], params?: Record<string, string | number>) => {
    let str = translations[language]?.[key] || translations['en']?.[key] || translations['ja']?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }
    return str;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

